# The LLM used for reverse generation (use a single LLM for consistency)
REVERSE_GEN_MODEL = "qwen-max"

REVERSE_PROMPT_TEMPLATE = """You are an expert in ontology engineering and SPARQL. Given the following SPARQL query that was generated for a specific ontology, your task is to reverse-engineer the original natural language competency question that this query was designed to answer.

## SPARQL Query
```sparql
{sparql_query}
```

## Ontology Triples (context)
{triples_context}

## Instructions
1. Analyze the SPARQL query structure: its SELECT variables, WHERE patterns, and any FILTER/OPTIONAL clauses.
2. Identify which ontology concepts, properties, and relationships the query references.
3. Formulate a single natural language question that this SPARQL query would answer.
4. The question should be clear, concise, and phrased as a competency question about the ontology.

## Output
Output ONLY the natural language question, without any explanations, prefixes like "[Simple]" or "[Complex]", or additional text.
"""


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_llm_configs() -> dict:
    with open(LLM_CONFIGS_PATH, "r") as f:
        return json.load(f)


def create_openai_client(llm_config: dict) -> openai.OpenAI:
    """Create an OpenAI-compatible client from config."""
    if llm_config.get("api_type") == "azure":
        return openai.AzureOpenAI(
            api_key=llm_config["api_key"],
            azure_endpoint=llm_config["base_url"],
            api_version=llm_config.get("api_version", "2024-12-01-preview"),
        )
    else:
        return openai.OpenAI(
            api_key=llm_config["api_key"],
            base_url=llm_config["base_url"],
        )


def extract_qualified_questions(run_dir: str) -> List[Dict]:
    """Extract all qualified questions from the last iteration of each subgraph.

    Returns list of dicts with keys: question, sparql_query, query_result, subgraph_id
    """
    files = sorted(glob.glob(os.path.join(run_dir, "subgraph_*_iter_*.json")))
    if not files:
        return []

    # Group by subgraph_id, keep last iteration
    sg_files = {}
    for f in files:
        base = os.path.basename(f).replace(".json", "")
        parts = base.split("_")
        sg_id = int(parts[1])
        iter_id = int(parts[3])
        if sg_id not in sg_files or iter_id > sg_files[sg_id][1]:
            sg_files[sg_id] = (f, iter_id)

    all_qq = []
    seen_questions = set()
    for sg_id, (filepath, _) in sorted(sg_files.items()):
        with open(filepath, "r") as f:
            data = json.load(f)
        for qq in data.get("qualified_questions", []):
            q_text = qq["question"]
            if q_text not in seen_questions:
                seen_questions.add(q_text)
                all_qq.append({
                    "question": q_text,
                    "sparql_query": qq.get("sparql_query", ""),
                    "query_result": qq.get("query_result", []),
                    "subgraph_id": sg_id,
                })
    return all_qq


def load_ontology_triples(dataset: str) -> str:
    """Load ontology triples for context in reverse generation prompt.

    Returns a truncated string representation of the triples.
    """
    # Try to load from the run directory's results.json
    dataset_dir = os.path.join(
        os.path.dirname(SCRIPT_DIR), "OntologyAgent", "dataset", dataset
    )
    json_path = os.path.join(dataset_dir, f"{dataset}.json")
    if os.path.exists(json_path):
        with open(json_path, "r") as f:
            data = json.load(f)
        triples = data.get("triples", [])
        # Truncate to avoid prompt being too long
        triples_str = str(triples[:50])
        if len(triples) > 50:
            triples_str += f"\n... ({len(triples)} triples total, showing first 50)"
        return triples_str
    return "(triples not available)"


def get_subgraph_triples(run_dir: str, subgraph_id: int) -> str:
    """Load the specific subgraph triples from the last iteration file."""
    files = sorted(glob.glob(
        os.path.join(run_dir, f"subgraph_{subgraph_id}_iter_*.json")
    ))
    if not files:
        return "(subgraph triples not available)"

    # Use the first iteration (has the original triples before any modification)
    with open(files[0], "r") as f:
        data = json.load(f)

    # The subgraph file doesn't directly contain triples, but we can get context
    # from the competency questions and SPARQL queries
    cqs = data.get("competency_questions", [])
    return f"(Subgraph {subgraph_id} context - {len(cqs)} CQs generated for this subgraph)"


def strip_cq_prefix(cq: str) -> str:
    """Remove [Simple] or [Complex] prefix from CQ text."""
    return re.sub(r"^\[(Simple|Complex)\]\s*", "", cq).strip()


def reverse_generate_cq(
    client: openai.OpenAI,
    model: str,
    sparql_query: str,
    triples_context: str,
    max_retries: int = 3,
) -> Optional[str]:
    """Use LLM to reverse-generate a CQ from a SPARQL query."""
    prompt = REVERSE_PROMPT_TEMPLATE.format(
        sparql_query=sparql_query,
        triples_context=triples_context,
    )

    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.1,
                max_tokens=256,
            )
            result = response.choices[0].message.content.strip()
            # Clean up the result
            result = result.strip('"').strip("'")
            result = re.sub(r"^\[(Simple|Complex)\]\s*", "", result)
            return result
        except Exception as e:
            print(f"  [retry {attempt+1}/{max_retries}] LLM call failed: {e}")
            time.sleep(2 ** attempt)

    return None


def compute_sbert_similarity(cq_original: str, cq_reverse: str, model) -> float:
    """Compute SBERT cosine similarity between two CQ texts."""
    emb = model.encode([cq_original, cq_reverse], convert_to_tensor=True)
    score = util.cos_sim(emb[0], emb[1]).item()
    return score


# ---------------------------------------------------------------------------
# Main experiment
# ---------------------------------------------------------------------------

def run_experiment(
    dataset_filter: Optional[str] = None,
    model_filter: Optional[str] = None,
    dry_run: bool = False,
    limit: int = 0,
    force: bool = False,
):
    """Run the RTS experiment."""
    os.makedirs(RTS_OUTPUT_DIR, exist_ok=True)

    llm_configs = load_llm_configs()
    reverse_config = llm_configs[REVERSE_GEN_MODEL]
    reverse_client = create_openai_client(reverse_config)
    reverse_model_name = reverse_config["model"]

    print(f"Reverse generation LLM: {REVERSE_GEN_MODEL}")
    print(f"Loading SBERT model...")
    sbert_model = SentenceTransformer("all-MiniLM-L6-v2")
    print(f"SBERT model loaded.\n")

    # Results storage
    all_results = {}

    datasets_to_run = (
        {dataset_filter: RUN_DIRS[dataset_filter]}
        if dataset_filter and dataset_filter in RUN_DIRS
        else RUN_DIRS
    )

    for dataset, models in datasets_to_run.items():
        all_results[dataset] = {}
        # Load ontology triples once per dataset
        ont_triples_str = load_ontology_triples(dataset)

        models_to_run = (
            {model_filter: models[model_filter]}
            if model_filter and model_filter in models
            else models
        )

        for gen_model, run_dir in models_to_run.items():
            print(f"\n{'='*60}")
            print(f"Dataset: {dataset} | Generator LLM: {gen_model}")
            print(f"Run dir: {run_dir}")
            print(f"{'='*60}")

            # Extract qualified questions
            qualified_cqs = extract_qualified_questions(run_dir)
            print(f"Found {len(qualified_cqs)} unique qualified CQs")

            if limit > 0:
                qualified_cqs = qualified_cqs[:limit]
                print(f"(Limited to first {limit} CQs)")

            if dry_run:
                print("[DRY RUN] Skipping LLM calls and SBERT computation")
                all_results[dataset][gen_model] = {
                    "total_cqs": len(qualified_cqs),
                    "rts_scores": [],
                    "avg_rts": 0.0,
                }
                continue

            # Check for existing results (resume support)
            out_path = os.path.join(
                RTS_OUTPUT_DIR, f"rts_{dataset}_{gen_model}.json"
            )
            if not force and os.path.exists(out_path):
                with open(out_path, "r") as f:
                    existing = json.load(f)
                if existing.get("processed_cqs", 0) > 0:
                    print(f"  SKIPPED: Found existing results with {existing['processed_cqs']} CQs (use --force to overwrite)")
                    all_results[dataset][gen_model] = existing
                    continue

            rts_scores = []
            details = []

            for i, qq in enumerate(qualified_cqs):
                original_cq = strip_cq_prefix(qq["question"])
                sparql = qq["sparql_query"]

                if not sparql or sparql.strip() == "":
                    print(f"  [{i+1}/{len(qualified_cqs)}] SKIP - no SPARQL query")
                    continue

                # Build context for the prompt
                context = ont_triples_str

                # Reverse generate CQ'
                print(f"  [{i+1}/{len(qualified_cqs)}] Reverse-generating CQ'...", end=" ")
                cq_prime = reverse_generate_cq(
                    reverse_client, reverse_model_name, sparql, context
                )

                if cq_prime is None:
                    print("FAILED")
                    continue

                # Compute SBERT similarity
                rts = compute_sbert_similarity(original_cq, cq_prime, sbert_model)
                rts_scores.append(rts)

                detail = {
                    "original_cq": qq["question"],
                    "sparql_query": sparql,
                    "reverse_cq": cq_prime,
                    "rts_score": round(rts, 4),
                    "subgraph_id": qq["subgraph_id"],
                }
                details.append(detail)

                print(f"RTS={rts:.4f} | CQ': {cq_prime[:60]}...")

            avg_rts = sum(rts_scores) / len(rts_scores) if rts_scores else 0.0

            result = {
                "dataset": dataset,
                "generator_model": gen_model,
                "reverse_gen_model": REVERSE_GEN_MODEL,
                "total_qualified_cqs": len(qualified_cqs),
                "processed_cqs": len(rts_scores),
                "avg_rts": round(avg_rts, 4),
                "median_rts": round(sorted(rts_scores)[len(rts_scores)//2], 4) if rts_scores else 0.0,
                "min_rts": round(min(rts_scores), 4) if rts_scores else 0.0,
                "max_rts": round(max(rts_scores), 4) if rts_scores else 0.0,
                "details": details,
            }

            all_results[dataset][gen_model] = result

            # Save per-dataset-model result
            with open(out_path, "w") as f:
                json.dump(result, f, ensure_ascii=False, indent=2)
            print(f"\nSaved to {out_path}")
            print(f"Avg RTS: {avg_rts:.4f} ({len(rts_scores)} CQs)")

    # Print summary table
    print(f"\n\n{'='*70}")
    print("ROUND-TRIP CONSISTENCY SCORE (RTS) SUMMARY")
    print(f"{'='*70}")
    print(f"{'Model':<12} {'OneM2M':>8} {'SAREF4ENV':>10} {'VGO':>8} {'VC':>8} {'Avg':>8}")
    print("-" * 70)

    dataset_keys = ["onem2m", "saref4env", "videogameontology", "vicinitycore"]
    dataset_labels = ["OneM2M", "SAREF4ENV", "VGO", "VC"]
    model_keys = ["qwen-max", "glm-5", "gpt-5"]

    grand_total = []
    for model in model_keys:
        row_scores = []
        for ds in dataset_keys:
            r = all_results.get(ds, {}).get(model, {})
            score = r.get("avg_rts", 0.0) if isinstance(r, dict) else 0.0
            row_scores.append(score)
        avg = sum(row_scores) / len(row_scores) if row_scores else 0.0
        grand_total.extend(row_scores)
        print(
            f"{model:<12} "
            + "  ".join(f"{s:>8.4f}" for s in row_scores)
            + f"  {avg:>8.4f}"
        )

    # Dataset averages
    print("-" * 70)
    avg_row = []
    for ds in dataset_keys:
        ds_scores = []
        for model in model_keys:
            r = all_results.get(ds, {}).get(model, {})
            s = r.get("avg_rts", 0.0) if isinstance(r, dict) else 0.0
            ds_scores.append(s)
        avg_row.append(sum(ds_scores) / len(ds_scores) if ds_scores else 0.0)
    grand_avg = sum(grand_total) / len(grand_total) if grand_total else 0.0
    print(
        f"{'Avg':<12} "
        + "  ".join(f"{s:>8.4f}" for s in avg_row)
        + f"  {grand_avg:>8.4f}"
    )

    # Save summary
    summary = {
        "experiment": "Round-Trip Consistency (RTS)",
        "reverse_gen_model": REVERSE_GEN_MODEL,
        "sbert_model": "all-MiniLM-L6-v2",
        "results": {},
    }
    for ds in dataset_keys:
        summary["results"][ds] = {}
        for model in model_keys:
            r = all_results.get(ds, {}).get(model, {})
            if isinstance(r, dict):
                summary["results"][ds][model] = {
                    "avg_rts": r.get("avg_rts", 0.0),
                    "processed_cqs": r.get("processed_cqs", 0),
                    "total_qualified_cqs": r.get("total_qualified_cqs", 0),
                }
    summary_path = os.path.join(RTS_OUTPUT_DIR, "rts_summary.json")
    with open(summary_path, "w") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)
    print(f"\nSummary saved to {summary_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="RTS Experiment")
    parser.add_argument("--dataset", type=str, help="Run only this dataset")
    parser.add_argument("--model", type=str, help="Run only this generator model")
    parser.add_argument("--dry-run", action="store_true", help="Preview without LLM calls")
    parser.add_argument("--limit", type=int, default=0, help="Limit CQs per run (0=all)")
    parser.add_argument("--force", action="store_true", help="Overwrite existing results")
    args = parser.parse_args()

    run_experiment(
        dataset_filter=args.dataset,
        model_filter=args.model,
        dry_run=args.dry_run,
        limit=args.limit,
        force=args.force,
    )
