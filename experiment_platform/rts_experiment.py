#!/usr/bin/env python3
"""Round-Trip Consistency (RTS) Experiment for CQGen-MAS.

For each qualified CQ generated by CQGen-MAS, we:
1. Extract the (CQ, SPARQL_query, query_result) triple from intermediate results
2. Use an LLM to reverse-generate a natural language question CQ' from the
   SPARQL query (and its execution context / ontology triples)
3. Compute SBERT cosine similarity between original CQ and CQ'
4. Report average RTS per dataset × LLM

Usage:
    python rts_experiment.py                    # run all
    python rts_experiment.py --dataset onem2m   # run one dataset
    python rts_experiment.py --dry-run          # preview without LLM calls
"""

